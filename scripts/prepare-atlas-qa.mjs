import {mkdtemp,mkdir,cp,writeFile,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const repo=fileURLToPath(new URL('../',import.meta.url));
const root=await mkdtemp(join(tmpdir(),'travel-globe-atlas-qa-'));
const vault=join(root,'vault'),profile=join(root,'profile');
await mkdir(vault+'/.obsidian/plugins/travel-globe',{recursive:true});await mkdir(profile,{recursive:true});
for(const name of ['main.js','manifest.json','styles.css','LICENSE','THIRD_PARTY_NOTICES.md','安装说明.md'])await cp(resolve(repo,name),vault+'/.obsidian/plugins/travel-globe/'+name);
await cp(resolve(repo,'runtime-assets'),vault+'/.obsidian/plugins/travel-globe/runtime-assets',{recursive:true});
await cp(resolve(repo,'examples/旅行记录'),vault+'/示例旅行记录',{recursive:true});
await cp(resolve(repo,'examples/附件'),vault+'/附件',{recursive:true});
await writeFile(vault+'/.obsidian/community-plugins.json',JSON.stringify(['travel-globe']));
await writeFile(vault+'/.obsidian/core-plugins.json','[]');
await writeFile(vault+'/.obsidian/app.json',JSON.stringify({promptDelete:false}));
await writeFile(vault+'/.obsidian/plugins/travel-globe/data.json',JSON.stringify({recordsFolder:'示例旅行记录',attachmentsFolder:'附件',earthOnline:false,satelliteOnline:false,settingsVersion:4}));
await writeFile(profile+'/obsidian.json',JSON.stringify({vaults:{aabbccddeeff1122:{path:vault,ts:Date.now(),open:true}}}));
const manifest=JSON.parse(await readFile(resolve(repo,'manifest.json'),'utf8'));
const spec={root,vault,profile,version:manifest.version,port:9224};
await writeFile(root+'/qa.json',JSON.stringify(spec,null,2)+'\n');
console.log(JSON.stringify(spec,null,2));
